"""MITRE ATT&CK coverage matrix generation.

Outputs (deterministic, committed and checked for drift in CI):

* ``coverage/attack_navigator_layer.json`` - layer for the ATT&CK Navigator
  (https://mitre-attack.github.io/attack-navigator/), score = number of rules
* ``coverage/COVERAGE.md`` - Markdown summary, per-tactic and per-technique tables
  and the rule inventory with the generated Wazuh rule IDs
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from pathlib import Path

from opensoc_detections import attack
from opensoc_detections.config import COVERAGE_DIR, RULES_DIR, ROOT, mapping_for
from opensoc_detections.loader import load_rule, rule_files
from opensoc_detections.wazuh.ids import RuleIdRegistry

NAVIGATOR_VERSION = "5.2.0"
LAYER_VERSION = "4.5"
LEVEL_ORDER = ["critical", "high", "medium", "low", "informational"]
PLATFORM_NAMES = {"windows": "Windows", "linux": "Linux", "network": "Network", "cloud": "Cloud"}
NAVIGATOR_PLATFORMS = {
    "windows": ["Windows"],
    "linux": ["Linux"],
    "network": ["Network Devices"],
    "cloud": ["IaaS", "SaaS", "Office Suite", "Identity Provider"],
}


@dataclass
class RuleInfo:
    id: str
    title: str
    level: str
    status: str
    path: str
    platform: str
    logsource: str
    techniques: list[str]
    tactics: list[str]
    wazuh_ids: list[int] = field(default_factory=list)


def collect(paths: list[Path] | None = None, registry: RuleIdRegistry | None = None,
            branch_counts: dict[str, int] | None = None) -> list[RuleInfo]:
    data = attack.load()
    registry = registry or RuleIdRegistry()
    infos = []
    for p in paths or rule_files():
        rule = load_rule(p)
        techniques, tactic_tags = attack.parse_tags(str(t) for t in rule.tags)
        tactics = [data.tactic_by_tag(t).shortname for t in tactic_tags if data.tactic_by_tag(t)]
        rel = p.resolve().relative_to(RULES_DIR.resolve())
        mapping = mapping_for(rule.logsource)
        base = registry.get(str(rule.id))
        count = (branch_counts or {}).get(str(rule.id), 1)
        infos.append(
            RuleInfo(
                id=str(rule.id),
                title=rule.title,
                level=rule.level.name.lower() if rule.level else "medium",
                status=rule.status.name.lower() if rule.status else "",
                path=str(Path("rules") / rel),
                platform=rel.parts[0],
                logsource=mapping.id if mapping else "unmapped",
                techniques=techniques,
                tactics=tactics,
                wazuh_ids=[base + i for i in range(count)] if base is not None else [],
            )
        )
    infos.sort(key=lambda r: (r.platform, r.path))
    return infos


def _technique_tactics(rule: RuleInfo, tid: str) -> list[str]:
    tech = attack.load().technique(tid)
    if tech is None:
        return []
    return [t for t in tech.tactics if t in rule.tactics] or list(tech.tactics)


def navigator_layer(rules: list[RuleInfo]) -> dict:
    data = attack.load()
    cells: dict[tuple[str, str], list[RuleInfo]] = defaultdict(list)
    for r in rules:
        for tid in r.techniques:
            for tac in _technique_tactics(r, tid):
                cells[(tid, tac)].append(r)
    max_score = max((len(v) for v in cells.values()), default=1)
    techniques = []
    for (tid, tac), covering in sorted(cells.items(), key=lambda kv: (kv[0][0], kv[0][1])):
        levels = Counter(r.level for r in covering)
        techniques.append(
            {
                "techniqueID": tid,
                "tactic": tac,
                "score": len(covering),
                "color": "",
                "comment": "; ".join(f"{r.title} [{r.level}]" for r in covering),
                "enabled": True,
                "metadata": [{"name": "rule", "value": f"{r.title} ({r.level}) - {r.path}"} for r in covering]
                + [{"name": "levels", "value": ", ".join(f"{lv}: {levels[lv]}" for lv in LEVEL_ORDER if levels[lv])}],
                "links": [],
                "showSubtechniques": True,
            }
        )
    platforms = sorted({p for r in rules for p in NAVIGATOR_PLATFORMS.get(r.platform, [])})
    return {
        "name": "OpenSOC Sigma detections",
        "versions": {"attack": data.version.split(".")[0], "navigator": NAVIGATOR_VERSION, "layer": LAYER_VERSION},
        "domain": "enterprise-attack",
        "description": (
            f"Coverage of {len(rules)} OpenSOC Sigma rules over MITRE ATT&CK Enterprise v{data.version}. "
            "Score = number of rules detecting the technique. Generated by opensoc-detections, do not edit."
        ),
        "filters": {"platforms": platforms},
        "sorting": 3,
        "layout": {
            "layout": "side",
            "aggregateFunction": "max",
            "showID": True,
            "showName": True,
            "showAggregateScores": True,
            "countUnscored": False,
            "expandedSubtechniques": "annotated",
        },
        "hideDisabled": False,
        "techniques": techniques,
        "gradient": {"colors": ["#c6e7ffff", "#2b83baff", "#08306bff"], "minValue": 0, "maxValue": max_score},
        "legendItems": [
            {"label": "Covered by 1 rule", "color": "#c6e7ff"},
            {"label": f"Covered by {max_score} rules", "color": "#08306b"},
        ],
        "metadata": [
            {"name": "rules", "value": str(len(rules))},
            {"name": "techniques", "value": str(len({r_t for r in rules for r_t in r.techniques}))},
            {"name": "generator", "value": "opensoc-detections (detections/opensoc_detections/coverage.py)"},
        ],
        "links": [],
        "showTacticRowBackground": True,
        "tacticRowBackground": "#dddddd",
        "selectTechniquesAcrossTactics": True,
        "selectSubtechniquesWithParent": False,
        "selectVisibleTechniques": False,
    }


def _md_escape(text: str) -> str:
    return text.replace("|", "\\|")


def markdown(rules: list[RuleInfo]) -> str:
    data = attack.load()
    by_technique: dict[str, list[RuleInfo]] = defaultdict(list)
    for r in rules:
        for tid in r.techniques:
            by_technique[tid].append(r)
    tactic_techniques: dict[str, set[str]] = defaultdict(set)
    tactic_rules: dict[str, set[str]] = defaultdict(set)
    for r in rules:
        for tid in r.techniques:
            for tac in _technique_tactics(r, tid):
                tactic_techniques[tac].add(tid)
                tactic_rules[tac].add(r.id)
    covered_tactics = [t for t in data.tactics if tactic_techniques.get(t.shortname)]
    parents = {tid.split(".")[0] for tid in by_technique}
    subs = [t for t in by_technique if "." in t]
    levels = Counter(r.level for r in rules)
    platforms = Counter(r.platform for r in rules)

    out = [
        "# OpenSOC - MITRE ATT&CK coverage",
        "",
        "> Generated by `python -m opensoc_detections coverage` from `detections/rules`. Do not edit by hand.",
        f"> ATT&CK Enterprise **v{data.version}** - load `attack_navigator_layer.json` in the "
        "[ATT&CK Navigator](https://mitre-attack.github.io/attack-navigator/) (*Open Existing Layer > Upload from local*).",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Sigma rules | {len(rules)} |",
        f"| Wazuh rules generated | {sum(len(r.wazuh_ids) for r in rules)} |",
        f"| ATT&CK IDs covered | {len(by_technique)} ({len(subs)} sub-techniques, {len(parents)} distinct techniques) |",
        f"| Tactics covered | {len(covered_tactics)} / {len(data.tactics)} |",
        "| Rules by platform | " + ", ".join(f"{PLATFORM_NAMES.get(p, p)}: {n}" for p, n in sorted(platforms.items())) + " |",
        "| Rules by level | " + ", ".join(f"{lv}: {levels[lv]}" for lv in LEVEL_ORDER if levels[lv]) + " |",
        "",
        "## Coverage by tactic",
        "",
        "| Tactic | ID | Techniques covered | Rules | Covered techniques |",
        "|---|---|---:|---:|---|",
    ]
    for tac in data.tactics:
        techs = sorted(tactic_techniques.get(tac.shortname, set()))
        out.append(
            f"| {tac.name} | {tac.id} | {len(techs)} | {len(tactic_rules.get(tac.shortname, set()))} | "
            + (", ".join(techs) if techs else "-") + " |"
        )
    out += [
        "",
        "## Coverage by technique",
        "",
        "| Technique | Name | Tactics | Rules | Max level | Platforms |",
        "|---|---|---|---:|---|---|",
    ]
    for tid in sorted(by_technique):
        tech = data.technique(tid)
        covering = by_technique[tid]
        max_level = min((r.level for r in covering), key=LEVEL_ORDER.index)
        tacs = sorted({t for r in covering for t in _technique_tactics(r, tid)}, key=data.tactic_shortnames.index)
        out.append(
            f"| [{tid}]({tech.url}) | {_md_escape(tech.full_name)} | {', '.join(tacs)} | {len(covering)} | {max_level} | "
            + ", ".join(sorted({PLATFORM_NAMES.get(r.platform, r.platform) for r in covering})) + " |"
        )
    out += [
        "",
        "## Rule inventory",
        "",
        "| Rule | Level | Status | Logsource | ATT&CK | Wazuh rule IDs |",
        "|---|---|---|---|---|---|",
    ]
    for r in rules:
        ids = ", ".join(str(i) for i in r.wazuh_ids) if r.wazuh_ids else "-"
        out.append(
            f"| [{_md_escape(r.title)}](../{r.path}) | {r.level} | {r.status} | {r.logsource} | "
            f"{', '.join(r.techniques)} | {ids} |"
        )
    out.append("")
    return "\n".join(out)


def write(rules: list[RuleInfo], out_dir: Path = COVERAGE_DIR) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    layer_path = out_dir / "attack_navigator_layer.json"
    md_path = out_dir / "COVERAGE.md"
    layer_path.write_text(json.dumps(navigator_layer(rules), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    md_path.write_text(markdown(rules), encoding="utf-8")
    return layer_path, md_path


__all__ = ["collect", "navigator_layer", "markdown", "write", "ROOT"]
